// Generates a .env file with strong random secrets so the server can start.
// Usage: npm run setup:env        (will not overwrite an existing .env unless --force is passed)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const envPath = path.resolve(process.cwd(), '.env');
const force = process.argv.includes('--force');

if (fs.existsSync(envPath) && !force) {
  console.log('.env already exists - nothing changed. Use "npm run setup:env -- --force" to regenerate it.');
  process.exit(0);
}

const secret = () => crypto.randomBytes(32).toString('hex');
const organizerCode = `ORG-${crypto.randomBytes(6).toString('hex').toUpperCase()}`;

const content = `# Generated by scripts/setup-env.mjs - never commit this file.
PORT=3000

# --- Required secrets (server refuses to start without them) ---
JWT_SECRET=${secret()}
DATA_ENCRYPTION_KEY=${secret()}
ORGANIZER_SETUP_CODE=${organizerCode}

# --- MongoDB (primary database). Paste your MongoDB Atlas / local connection string here ---
# Example: mongodb+srv://<user>:<password>@cluster0.xxxxx.mongodb.net/eventsphere
MONGODB_URI=

# --- Optional ---
# Extra allowed browser origins for Socket.io, comma separated (same-origin is always allowed in production)
CLIENT_ORIGIN=
# Redirect all HTTP to HTTPS when deployed behind a TLS proxy (Render, Railway, Nginx...)
FORCE_HTTPS=
# SMTP for password-reset OTP e-mails
SMTP_HOST=
SMTP_PORT=
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM_EMAIL=
`;

fs.writeFileSync(envPath, content, { encoding: 'utf8', mode: 0o600 });
console.log('Created .env with fresh random secrets.');
console.log(`Organizer sign-up invite code: ${organizerCode}`);
console.log('Next: add your MONGODB_URI to .env, then run "npm run dev".');
